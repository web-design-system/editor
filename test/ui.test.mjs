import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("landing page lists teams and design systems without depending on component artifacts", async () => {
  const html = await readFile(new URL("../public/index.html", import.meta.url), "utf8");
  const app = await readFile(new URL("../public/app.mjs", import.meta.url), "utf8");
  assert.match(html, /id="team-list"/);
  assert.match(html, /id="system-grid"/);
  assert.match(html, /id="team-form"/);
  assert.match(html, /id="system-form"/);
  assert.match(html, /id="creation-controls"[^>]*hidden/);
  assert.match(html, /Teams own design systems/);
  assert.match(html, /Git organization slug/);
  assert.match(app, /fetch\("\/api\/teams"/);
  assert.match(app, /fetch\("\/api\/design-systems"/);
  assert.match(app, /\/\?team=\$\{encodeURIComponent\(system\.org \|\| system\.team\)\}&amp;repo=/);
  assert.match(app, /\/api\/oidc\/me/);
  assert.match(app, /\/api\/oidc\/login/);
  assert.match(app, /fetch\("\/api\/teams", \{/);
  assert.match(app, /teamForm\.addEventListener\("submit"/);
  assert.match(app, /systemForm\.addEventListener\("submit"/);
  assert.match(app, /Sign-in could not be completed/);
  assert.doesNotMatch(html, /<wds-[a-z-]+/);
});

test("workbench exposes project source and authoring workflows", async () => {
  const html = await readFile(new URL("../public/index.html", import.meta.url), "utf8");
  const app = await readFile(new URL("../public/app.mjs", import.meta.url), "utf8");
  const editor = await readFile(new URL("../public/code-editor.mjs", import.meta.url), "utf8");
  assert.match(app, /const team = params\.get\("team"\)/);
  assert.match(app, /const repo = params\.get\("repo"\)/);
  assert.match(app, /workspace\.style\.display = "block"/);
  assert.match(html, /id="workspace-user-card"/);
  assert.match(html, /id="project-content"/);
  assert.match(app, /api\/source/);
  assert.match(app, /api\/history/);
  assert.match(app, /data-wds-editable/);
  assert.match(app, /Draft preview \(sandboxed, no component scripts\)/);
  assert.match(app, /api\/publish/);
  assert.match(app, /component-create/);
  assert.match(app, /designSystem: \{ team, repo, revision: "latest" \}/);
  assert.match(app, /published tokens\.css at the latest revision/);
  assert.match(app, /tokens-editor/);
  assert.match(app, /save-tokens/);
  assert.match(app, /publish-tokens/);
  assert.match(app, /method: "HEAD", cache: "no-store"/);
  assert.match(app, /componentForm\.hidden = !response\.ok/);
  assert.match(app, /if \(response\.ok\) \{\s+await probePublishedTokens\(\)/);
  assert.match(app, /Component name/);
  assert.match(app, /repo: slug,\s+name,/);
  assert.doesNotMatch(app, /name="description"|Repository slug<input name="repo"/);
  assert.match(editor, /class WdsCodeEditor extends HTMLElement/);
  assert.match(editor, /<textarea/);
  assert.match(editor, /set value\(value\)/);
  assert.match(editor, /new Event\("input", \{ bubbles: true \}\)/);
  assert.match(editor, /event\.shiftKey/);
  assert.match(editor, /aria-live="polite"/);
});
